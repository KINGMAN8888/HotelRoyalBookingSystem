    private void showBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_showBtnActionPerformed
        new javax.swing.SwingWorker<java.util.List<Object[]>, Void>() {
            @Override
            protected java.util.List<Object[]> doInBackground() throws Exception {
                return new BookingDAO().getAllBookingsDetailed();
            }
            @Override
            protected void done() {
                try {
                    java.util.List<Object[]> bookings = get();
                    String[] cols = {"ID", "Customer Name", "Room No.", "Type",
                                     "Check-In", "Check-Out", "Nights", "Amount ($)", "Status", "RoomID", "Price"};
                    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(cols, 0) {
                        public boolean isCellEditable(int r, int c) { return false; }
                    };
                    viewTable.setModel(model);

                    for (Object[] row : bookings) {
                        long nights = calcNights((String) row[4], (String) row[5]);
                        model.addRow(new Object[]{
                            row[0], row[1], row[2], row[3], row[4], row[5],
                            nights > 0 ? String.valueOf(nights) : "—", row[6], row[7], row[8], row[9]
                        });
                    }

                    // Widen important columns
                    viewTable.getColumnModel().getColumn(1).setPreferredWidth(140);
                    viewTable.getColumnModel().getColumn(4).setPreferredWidth(85);
                    viewTable.getColumnModel().getColumn(5).setPreferredWidth(85);
                    viewTable.getColumnModel().getColumn(6).setPreferredWidth(55);

                    // Re-apply styles and renderers since the model replacement drops them
                    styleTable(viewTable);

                    // Hide RoomID (9) and Price (10) helper columns after styling
                    for (int ci : new int[]{9, 10}) {
                        viewTable.getColumnModel().getColumn(ci).setMinWidth(0);
                        viewTable.getColumnModel().getColumn(ci).setMaxWidth(0);
                        viewTable.getColumnModel().getColumn(ci).setWidth(0);
                    }

                    if (bookings.isEmpty()) {
                        JOptionPane.showMessageDialog(admin_dashboard.this,
                            "No bookings found.", "Info", JOptionPane.INFORMATION_MESSAGE);
                    }
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(admin_dashboard.this,
                        "Error loading bookings: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }.execute();
    }//GEN-LAST:event_showBtnActionPerformed

    private void AddRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddRoomActionPerformed
        String roomNumber = RoomNumber.getText().trim();
        String type       = cmbRoomType.getSelectedItem().toString();
        String priceStr   = price1.getText().trim();
        String availStr   = cmbAvailable.getSelectedItem().toString();

        if (roomNumber.isEmpty() || priceStr.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Room number and price are required.",
                "Missing Fields", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            boolean available = availStr.equalsIgnoreCase("Yes");
            RoomDAO roomDAO   = new RoomDAO();

            if (editingExisting && editingRoomId > 0) {
                // Update existing room — type, price, and availability
                double price = Double.parseDouble(priceStr);
                if (roomDAO.updateRoom(editingRoomId, type, price, available)) {
                    JOptionPane.showMessageDialog(this,
                        "Room " + roomNumber + " updated successfully!",
                        "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this,
                        "Failed to update room.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                // Add brand-new room
                double price = Double.parseDouble(priceStr);
                Room room = new Room(0, roomNumber, type, price, available);
                if (roomDAO.addRoom(room)) {
                    JOptionPane.showMessageDialog(this,
                        "Room added successfully!",
                        "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this,
                        "Failed to add room.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            // Reset form
            RoomNumber.setText("");
            price1.setText("");
            cmbAvailable.setSelectedIndex(0);
            editingExisting = false;
            editingRoomId   = -1;
            AddRoom.setText("Add Room");
            loadRooms();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                "Please enter a valid number for price.",
                "Invalid Input", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                "Error: " + ex.getMessage(),
                "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_AddRoomActionPerformed

