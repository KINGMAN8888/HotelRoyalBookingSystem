    private void loadStatistics() {
        new javax.swing.SwingWorker<java.util.Map<String, String>, Void>() {
            @Override
            protected java.util.Map<String, String> doInBackground() throws Exception {
                java.util.Map<String, String> stats = new java.util.HashMap<>();
                double revenue = new BookingDAO().calculateRevenue();
                stats.put("revenue", String.format("$%.0f", revenue));

                try (java.sql.Connection conn = hotel.database.DatabaseConnection.getConnection()) {
                    int totalRooms  = queryInt(conn, "SELECT COUNT(*) FROM rooms");
                    int bookedRooms = queryInt(conn,
                        "SELECT COUNT(DISTINCT room_id) FROM bookings WHERE status IN ('Confirmed','CheckedIn')");
                    stats.put("totalRooms", String.valueOf(totalRooms));
                    stats.put("availableRooms", String.valueOf(totalRooms - bookedRooms));
                    stats.put("bookedRooms", String.valueOf(bookedRooms));
                    stats.put("totalBookings", String.valueOf(queryInt(conn, "SELECT COUNT(*) FROM bookings")));
                    stats.put("customers", String.valueOf(queryInt(conn, "SELECT COUNT(*) FROM users WHERE role='customer'")));
                }
                return stats;
            }
            @Override
            protected void done() {
                try {
                    java.util.Map<String, String> stats = get();
                    statTotalRooms.setText(stats.get("totalRooms"));
                    statAvailable.setText(stats.get("availableRooms"));
                    statBooked.setText(stats.get("bookedRooms"));
                    statBookings.setText(stats.get("totalBookings"));
                    statRevenue.setText(stats.get("revenue"));
                    statCustomers.setText(stats.get("customers"));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(admin_dashboard.this,
                        "Error loading statistics: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }.execute();
    }

    private int queryInt(java.sql.Connection conn, String sql) throws java.sql.SQLException {
        try (java.sql.Statement st = conn.createStatement();
             java.sql.ResultSet rs = st.executeQuery(sql)) {
            return rs.next() ? rs.getInt(1) : 0;
        }
    }

    private double queryDouble(java.sql.Connection conn, String sql) throws java.sql.SQLException {
        try (java.sql.Statement st = conn.createStatement();
             java.sql.ResultSet rs = st.executeQuery(sql)) {
            return rs.next() ? rs.getDouble(1) : 0.0;
        }
    }

    private long calcNights(String checkIn, String checkOut) {
        try {
            java.time.LocalDate ci = parseDate(checkIn);
            java.time.LocalDate co = parseDate(checkOut);
            if (ci == null || co == null) return 0;
            long n = java.time.temporal.ChronoUnit.DAYS.between(ci, co);
            return n > 0 ? n : 0;
        } catch (Exception e) {
            return 0;
        }
    }

    private java.time.LocalDate parseDate(String d) {
        if (d == null || d.isBlank()) return null;
        d = d.trim();
        for (String pat : new String[]{"yyyy-MM-dd", "dd/MM/yyyy", "MM/dd/yyyy", "dd-MM-yyyy"}) {
            try {
                return java.time.LocalDate.parse(d,
                    java.time.format.DateTimeFormatter.ofPattern(pat));
            } catch (Exception ignored) {}
        }
        return null;
    }

